from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path
from typing import Any

import numpy as np

PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))


def _read_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def _finite_or_none(x: Any) -> float | None:
    try:
        if x is None:
            return None
        v = float(x)
        if not math.isfinite(v):
            return None
        return v
    except Exception:
        return None


def _models(payload: dict[str, Any]) -> list[dict[str, Any]]:
    ms = payload.get("models", [])
    return [m for m in ms if isinstance(m, dict)]


def _ok_models(payload: dict[str, Any]) -> list[dict[str, Any]]:
    return [m for m in _models(payload) if not m.get("skipped")]


PRODUCTION_MODEL_NAME = "model"


def _filter_payload(payload: dict[str, Any], model_name: str) -> dict[str, Any]:
    """Return a copy of payload containing only the named model bundle."""
    filtered = [m for m in _models(payload) if str(m.get("name", "")) == model_name]
    return {**payload, "models": filtered}


def _ensure_out_dir(out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)


# Readable defaults: line charts + zoomed axes (metrics cluster near 1.0).
FIG_DPI = 150


def _tight_ylim(
    values: list[float],
    *,
    pad: float = 0.004,
    hi_cap: float | None = 1.0,
    min_span: float = 0.025,
    floor: float | None = None,
) -> tuple[float, float]:
    """Zoom y-axis around data; always includes all points with padding."""
    if not values:
        return 0.0, hi_cap if hi_cap is not None else 1.0
    lo = min(values)
    hi_data = max(values)
    y0 = lo - pad
    y1 = hi_data + pad
    if y1 - y0 < min_span:
        mid = (y0 + y1) / 2.0
        y0 = mid - min_span / 2.0
        y1 = mid + min_span / 2.0
    if floor is not None:
        y0 = max(y0, floor)
    if hi_cap is not None:
        y1 = min(y1, hi_cap)
        # If cap clips data, expand downward instead of hiding peaks.
        if y1 < hi_data + pad * 0.5:
            y1 = hi_cap
            y0 = min(y0, hi_data - max(min_span, hi_cap - hi_data) - pad)
    return y0, y1


def _short_label(name: str, max_len: int = 18) -> str:
    if len(name) <= max_len:
        return name
    return name[: max_len - 1] + "…"


def _legend_outside_right(ax, *, title: str | None = None) -> None:
    ax.legend(
        loc="center left",
        bbox_to_anchor=(1.02, 0.5),
        borderaxespad=0.0,
        frameon=False,
        title=title,
    )


def plot_auc_comparison(payload: dict[str, Any], out_dir: Path, *, title_suffix: str = "") -> Path:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    _ensure_out_dir(out_dir)
    out_path = out_dir / "model_auc_comparison.png"

    ms = _ok_models(payload)
    names = []
    aucs = []
    for m in ms:
        auc = _finite_or_none(m.get("auc"))
        if auc is None:
            continue
        names.append(str(m.get("name", "")))
        aucs.append(float(auc))

    if not names:
        fig, ax = plt.subplots(figsize=(8, 4))
        ax.text(0.5, 0.5, "No AUC values available", ha="center", va="center")
        ax.axis("off")
        fig.tight_layout()
        fig.savefig(out_path, dpi=FIG_DPI)
        plt.close(fig)
        return out_path

    title = f"Model comparison — AUC (zoomed scale){title_suffix}"

    if len(names) == 1:
        fig, ax = plt.subplots(figsize=(6, 5), constrained_layout=True)
        ax.bar([0], aucs, color="#1565C0", width=0.45, label="AUC")
        ax.text(0, aucs[0], f"{aucs[0]:.4f}", ha="center", va="bottom", fontsize=11, fontweight="bold")
        y0, y1 = _tight_ylim(aucs, pad=0.002, min_span=0.01, floor=0.0)
        ax.set_ylim(y0, y1)
        ax.set_xticks([0])
        ax.set_xticklabels([names[0]])
        ax.set_ylabel("AUC")
        ax.set_title(title)
        ax.grid(True, axis="y", alpha=0.3)
        fig.savefig(out_path, dpi=FIG_DPI, bbox_inches="tight", pad_inches=0.35)
        plt.close(fig)
        return out_path

    order = np.argsort(-np.asarray(aucs))
    names = [names[i] for i in order]
    aucs = [aucs[i] for i in order]
    x = np.arange(len(names))

    fig, ax = plt.subplots(figsize=(12, 5))
    ax.plot(x, aucs, color="#1565C0", marker="o", linewidth=2, markersize=7, label="AUC")
    for xi, yi in zip(x, aucs):
        ax.annotate(f"{yi:.4f}", (xi, yi), textcoords="offset points", xytext=(0, 8), ha="center", fontsize=8)

    y0, y1 = _tight_ylim(aucs, pad=0.002, min_span=0.01, floor=0.9)
    ax.set_ylim(y0, y1)
    ax.set_xticks(x)
    ax.set_xticklabels([_short_label(n) for n in names], rotation=35, ha="right")
    ax.set_ylabel("AUC")
    ax.set_title(title)
    ax.grid(True, alpha=0.3)
    _legend_outside_right(ax)
    fig.tight_layout(rect=[0.0, 0.0, 0.88, 1.0])
    fig.savefig(out_path, dpi=FIG_DPI)
    plt.close(fig)
    return out_path


def plot_metrics_comparison(payload: dict[str, Any], out_dir: Path, *, title_suffix: str = "") -> Path:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    _ensure_out_dir(out_dir)
    out_path = out_dir / "model_metrics_comparison.png"

    ms = _ok_models(payload)
    keys = ["accuracy", "precision", "tpr", "fpr"]
    colors = {
        "accuracy": "#1565C0",
        "precision": "#2E7D32",
        "tpr": "#6A1B9A",
        "fpr": "#C62828",
    }

    rows: list[dict[str, Any]] = []
    for m in ms:
        metrics = m.get("metrics") or {}
        row = {"name": str(m.get("name", ""))}
        ok = False
        for k in keys:
            v = _finite_or_none(metrics.get(k))
            row[k] = v
            ok = ok or (v is not None)
        if ok:
            rows.append(row)

    if not rows:
        fig, ax = plt.subplots(figsize=(8, 4))
        ax.text(0.5, 0.5, "No metric values available", ha="center", va="center")
        ax.axis("off")
        fig.tight_layout()
        fig.savefig(out_path, dpi=FIG_DPI)
        plt.close(fig)
        return out_path

    title = f"Model comparison — metrics @ bundle threshold (zoomed){title_suffix}"

    if len(rows) == 1:
        row = rows[0]
        metric_names = ["accuracy", "precision", "tpr", "fpr"]
        labels = [k.upper() for k in metric_names]
        vals = [float(row[k]) if row.get(k) is not None else np.nan for k in metric_names]
        bar_colors = [colors[k] for k in metric_names]

        fig, ax = plt.subplots(figsize=(8, 6), constrained_layout=True)
        x = np.arange(len(metric_names))
        ax.bar(x, vals, color=bar_colors, width=0.55)
        for xi, yi in zip(x, vals):
            if np.isfinite(yi):
                ax.text(xi, yi, f"{yi:.4f}", ha="center", va="bottom", fontsize=9)
        finite = [float(v) for v in vals if np.isfinite(v)]
        if finite:
            y0, y1 = _tight_ylim(finite, pad=0.004, hi_cap=1.0, min_span=0.012, floor=0.0)
            ax.set_ylim(y0, y1)
        ax.set_xticks(x)
        ax.set_xticklabels(labels, rotation=20, ha="right")
        ax.set_ylabel("Score")
        ax.set_title(f"{title}\n({row['name']})")
        ax.grid(True, axis="y", alpha=0.3)
        fig.savefig(out_path, dpi=FIG_DPI, bbox_inches="tight", pad_inches=0.35)
        plt.close(fig)
        return out_path

    names = [r["name"] for r in rows]
    x = np.arange(len(names))
    labels = [_short_label(n) for n in names]

    fig, (ax_main, ax_fpr) = plt.subplots(
        2,
        1,
        figsize=(12, 8),
        sharex=True,
        gridspec_kw={"height_ratios": [3, 1.2]},
        constrained_layout=True,
    )

    quality_keys = ["accuracy", "precision", "tpr"]
    quality_vals: list[float] = []
    for k in quality_keys:
        series = [float(r[k]) for r in rows if r.get(k) is not None]
        quality_vals.extend(series)
        ax_main.plot(
            x,
            [float(r[k]) if r.get(k) is not None else np.nan for r in rows],
            marker="o",
            linewidth=2,
            markersize=6,
            label=k.upper(),
            color=colors[k],
            alpha=0.9,
        )

    fpr_vals = [float(r["fpr"]) for r in rows if r.get("fpr") is not None]
    ax_fpr.plot(
        x,
        [float(r["fpr"]) if r.get("fpr") is not None else np.nan for r in rows],
        color=colors["fpr"],
        marker="s",
        linewidth=2,
        markersize=6,
        label="FPR",
    )
    ax_fpr.set_ylabel("FPR")
    if fpr_vals:
        f0, f1 = _tight_ylim(fpr_vals, pad=0.002, hi_cap=None, min_span=0.004, floor=0.0)
        ax_fpr.set_ylim(f0, f1)

    if quality_vals:
        q0, q1 = _tight_ylim(quality_vals, pad=0.004, hi_cap=1.0, min_span=0.012, floor=0.0)
        ax_main.set_ylim(q0, q1)
    ax_main.set_ylabel("Score")
    ax_main.set_title(title)
    ax_main.grid(True, alpha=0.3)
    ax_fpr.grid(True, alpha=0.3)
    ax_fpr.set_xticks(x)
    ax_fpr.set_xticklabels(labels, rotation=30, ha="right")
    ax_main.legend(loc="upper left", fontsize=9, framealpha=0.9, title="Metric")
    fig.savefig(out_path, dpi=FIG_DPI, bbox_inches="tight", pad_inches=0.35)
    plt.close(fig)
    return out_path


def plot_roc_curves(payload: dict[str, Any], out_dir: Path, *, title_suffix: str = "") -> Path:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from mpl_toolkits.axes_grid1.inset_locator import inset_axes

    _ensure_out_dir(out_dir)
    out_path = out_dir / "roc_curves.png"

    ms = _ok_models(payload)
    curves = []
    for m in ms:
        roc = m.get("roc")
        if not isinstance(roc, dict):
            continue
        fpr = roc.get("fpr")
        tpr = roc.get("tpr")
        if not isinstance(fpr, list) or not isinstance(tpr, list) or len(fpr) != len(tpr) or not fpr:
            continue
        curves.append((str(m.get("name", "")), np.asarray(fpr, dtype=float), np.asarray(tpr, dtype=float)))

    fig, ax = plt.subplots(figsize=(7, 7))
    if not curves:
        ax.text(0.5, 0.5, "ROC curves unavailable (rerun eval with --include-roc-points)", ha="center", va="center")
        ax.axis("off")
        fig.tight_layout()
        fig.savefig(out_path, dpi=FIG_DPI)
        plt.close(fig)
        return out_path

    for name, fpr, tpr in curves:
        ax.plot(fpr, tpr, linewidth=2, alpha=0.85, label=_short_label(name, 22))

    # Random baseline: y = x on [0, 1] with equal axis scaling (true 45° diagonal).
    ax.plot([0, 1], [0, 1], linestyle="--", color="gray", linewidth=1.2, alpha=0.65, label="Random")
    ax.set_xlim(0.0, 1.0)
    ax.set_ylim(0.0, 1.0)
    ax.set_aspect("equal", adjustable="box")
    ax.set_xlabel("False Positive Rate (FPR)")
    ax.set_ylabel("True Positive Rate (TPR)")
    ax.set_title(f"ROC curves{title_suffix}")
    ax.grid(True, alpha=0.3)

    # Inset zoom only for multi-model comparison (skip for single-model plots).
    if len(curves) > 1:
        max_fpr = 0.0
        min_tpr = 1.0
        for _, fpr, tpr in curves:
            mask = fpr <= 0.2
            if np.any(mask):
                max_fpr = max(max_fpr, float(np.max(fpr[mask])))
                min_tpr = min(min_tpr, float(np.min(tpr[mask])))
        x_hi = min(0.2, max(max_fpr * 1.35, 0.02))
        y_lo = max(0.0, min_tpr - 0.02)
        if x_hi < 1.0 and min_tpr < 1.0:
            axins = inset_axes(ax, width="42%", height="42%", loc="lower right", borderpad=1.2)
            for _, fpr, tpr in curves:
                axins.plot(fpr, tpr, linewidth=1.4, alpha=0.9)
            axins.set_xlim(0.0, x_hi)
            axins.set_ylim(y_lo, 1.002)
            axins.set_title("Low FPR zoom", fontsize=8)
            axins.tick_params(labelsize=7)
            axins.grid(True, alpha=0.25)

    if len(curves) > 1:
        _legend_outside_right(ax, title="Model")
        fig.tight_layout(rect=[0.0, 0.0, 0.78, 1.0])
    else:
        ax.legend(loc="lower right", fontsize=9, framealpha=0.9)
        fig.tight_layout()
    fig.savefig(out_path, dpi=FIG_DPI, bbox_inches="tight", pad_inches=0.25)
    plt.close(fig)
    return out_path


def plot_confusion_matrices(payload: dict[str, Any], out_dir: Path, *, title_suffix: str = "") -> Path:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    _ensure_out_dir(out_dir)
    out_path = out_dir / "confusion_matrices.png"

    ms = _ok_models(payload)
    mats: list[tuple[str, np.ndarray]] = []
    for m in ms:
        conf = m.get("confusion")
        if not isinstance(conf, dict):
            continue
        tn = conf.get("tn")
        fp = conf.get("fp")
        fn = conf.get("fn")
        tp = conf.get("tp")
        if not all(isinstance(v, (int, float)) for v in (tn, fp, fn, tp)):
            continue
        mat = np.array([[int(tn), int(fp)], [int(fn), int(tp)]], dtype=int)
        mats.append((str(m.get("name", "")), mat))

    if not mats:
        fig, ax = plt.subplots(figsize=(8, 4))
        ax.text(0.5, 0.5, "No confusion matrices available", ha="center", va="center")
        ax.axis("off")
        fig.tight_layout()
        fig.savefig(out_path, dpi=FIG_DPI)
        plt.close(fig)
        return out_path

    if len(mats) == 1:
        name, mat = mats[0]
        fig, ax = plt.subplots(figsize=(5.5, 4.5), constrained_layout=True)
        im = ax.imshow(mat, cmap="Blues", vmin=0, vmax=max(int(mat.max()), 1))
        ax.set_title(name)
        ax.set_xticks([0, 1])
        ax.set_yticks([0, 1])
        ax.set_xticklabels(["Pred 0", "Pred 1"])
        ax.set_yticklabels(["True 0", "True 1"])
        for (i, j), v in np.ndenumerate(mat):
            ax.text(j, i, str(int(v)), ha="center", va="center", color="black", fontsize=12)
        fig.colorbar(im, ax=ax, shrink=0.85, label="Count")
        fig.suptitle(f"Confusion matrix{title_suffix}", y=1.02)
        fig.savefig(out_path, dpi=FIG_DPI, bbox_inches="tight", pad_inches=0.35)
        plt.close(fig)
        return out_path

    n = len(mats)
    cols = min(3, n)
    rows = int(math.ceil(n / cols))
    fig, axes = plt.subplots(rows, cols, figsize=(4.5 * cols, 4.0 * rows))
    if not isinstance(axes, np.ndarray):
        axes = np.asarray([axes])
    axes = axes.reshape(rows, cols)

    vmax = max(int(mat.max()) for _, mat in mats) if mats else 1
    for idx in range(rows * cols):
        r, c = divmod(idx, cols)
        ax = axes[r, c]
        if idx >= n:
            ax.axis("off")
            continue
        name, mat = mats[idx]
        im = ax.imshow(mat, cmap="Blues", vmin=0, vmax=max(vmax, 1))
        ax.set_title(name)
        ax.set_xticks([0, 1])
        ax.set_yticks([0, 1])
        ax.set_xticklabels(["Pred 0", "Pred 1"])
        ax.set_yticklabels(["True 0", "True 1"])

        for (i, j), v in np.ndenumerate(mat):
            ax.text(j, i, str(int(v)), ha="center", va="center", color="black", fontsize=10)

    fig.suptitle(f"Confusion matrices (per model){title_suffix}", y=1.01)
    fig.tight_layout()

    # Shared colorbar
    cbar = fig.colorbar(im, ax=axes.ravel().tolist(), shrink=0.92)
    cbar.set_label("Count")

    fig.savefig(out_path, dpi=FIG_DPI, bbox_inches="tight")
    plt.close(fig)
    return out_path


def generate_all_figures(payload: dict[str, Any], out_dir: Path, *, title_suffix: str = "") -> dict[str, Path]:
    return {
        "auc": plot_auc_comparison(payload, out_dir, title_suffix=title_suffix),
        "metrics": plot_metrics_comparison(payload, out_dir, title_suffix=title_suffix),
        "roc": plot_roc_curves(payload, out_dir, title_suffix=title_suffix),
        "confusion": plot_confusion_matrices(payload, out_dir, title_suffix=title_suffix),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description="Plot model evaluation figures from model_eval.json.")
    parser.add_argument(
        "--in",
        dest="in_path",
        default=str(Path("report") / "model_eval" / "model_eval.json"),
        help="Input JSON from evaluate_saved_models.py (default: report/model_eval/model_eval.json)",
    )
    parser.add_argument(
        "--out-dir",
        default=str(Path("report") / "figures" / "model_eval"),
        help="Output directory for figures (default: report/figures/model_eval/)",
    )
    parser.add_argument(
        "--production-only",
        action="store_true",
        help="Only plot the production model.pkl (writes to <out-dir>/model_only/).",
    )
    args = parser.parse_args()

    in_path = Path(args.in_path)
    out_dir = Path(args.out_dir)
    if not in_path.exists():
        print(f"Missing input JSON: {in_path}")
        print("Run: `python scripts/evaluate_saved_models.py --include-roc-points`")
        return

    payload = _read_json(in_path)
    try:
        if not args.production_only:
            paths = generate_all_figures(payload, out_dir)
            for k, p in paths.items():
                print(f"Wrote [{k}]: {p}")

        prod_dir = out_dir / "model_only"
        prod_payload = _filter_payload(payload, PRODUCTION_MODEL_NAME)
        if not prod_payload.get("models"):
            print(f"No model named '{PRODUCTION_MODEL_NAME}' in {in_path}")
        else:
            prod_paths = generate_all_figures(
                prod_payload,
                prod_dir,
                title_suffix=f" — {PRODUCTION_MODEL_NAME}.pkl",
            )
            for k, p in prod_paths.items():
                print(f"Wrote [model_only/{k}]: {p}")
    except ModuleNotFoundError as exc:
        missing = getattr(exc, "name", None) or str(exc)
        print(
            "Missing required dependencies for plotting.\n"
            f"- Missing module: {missing}\n"
            "- Fix: install project requirements (matplotlib), e.g. `python -m pip install -r requirements.txt`"
        )
        return


if __name__ == "__main__":
    main()

